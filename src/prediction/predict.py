
import json
import joblib
import pandas as pd
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parents[2]
MODEL_DIR = BASE_DIR / "models"
FEATURE_DIR = BASE_DIR / "data" / "processed" / "features"



def load_best_model():
    """Load the best model selected during training."""

    metadata_path = MODEL_DIR / "best_model.json"

    if not metadata_path.exists():
        raise FileNotFoundError(
            f"Model metadata not found: {metadata_path}"
        )

    with open(metadata_path, "r") as file:
        metadata = json.load(file)

    # Support the metadata format generated by train_models.py.
    best_model = metadata.get("best_model") or metadata.get("model_name")

    if not best_model:
        raise ValueError(
            "best_model.json must contain 'best_model' or 'model_name'."
        )

    # Convert display names into model filenames.
    model_mapping = {
        "Random Forest": "random_forest",
        "Linear Regression": "linear_regression",
        "HistGradientBoosting": "histgradientboosting",
    }

    model_name = model_mapping.get(
        best_model,
        best_model.lower().replace(" ", "_")
    )

    model_path = MODEL_DIR / f"{model_name}.joblib"

    if not model_path.exists():
        raise FileNotFoundError(
            f"Model file not found: {model_path}"
        )

    model = joblib.load(model_path)

    return model, {
        **metadata,
        "model_name": model_name
    }



def load_latest_features():
    """Load the latest available processed feature data."""

    files = sorted(FEATURE_DIR.glob("*.parquet"))

    if not files:
        raise FileNotFoundError(
            f"No feature Parquet files found in {FEATURE_DIR}"
        )

    frames = []

    for file in files:
        df = pd.read_parquet(file)

        if not df.empty:
            frames.append(df)

    if not frames:
        raise ValueError("Feature files contain no records.")

    data = pd.concat(frames, ignore_index=True)

    data["date"] = pd.to_datetime(data["date"])

    return data


def prepare_prediction_data(data):
    """Prepare the latest available row for each product-store."""

    data = data.sort_values("date")

    latest = (
        data.groupby("id", as_index=False)
        .tail(1)
        .copy()
    )

    return latest


def predict_sales(data=None):
    """Generate predictions for the latest product-store records."""

    model, metadata = load_best_model()

    if data is None:
        data = load_latest_features()

    latest = prepare_prediction_data(data)

    # Exclude identifiers, dates, and target from model inputs.
    excluded = {
        "id",
        "date",
        "sales",
    }

    feature_columns = [
        column
        for column in latest.columns
        if column not in excluded
    ]

    X = latest[feature_columns]

    predictions = model.predict(X)

    results = latest[
        ["id", "date", "sales"]
    ].copy()

    results["predicted_sales"] = predictions.clip(min=0)

    results["model_name"] = metadata.get(
        "model_name",
        "Unknown"
    )

    return results


if __name__ == "__main__":
    predictions = predict_sales()

    output_dir = BASE_DIR / "data" / "processed" / "predictions"
    output_dir.mkdir(parents=True, exist_ok=True)

    output_file = output_dir / "latest_predictions.csv"

    predictions.to_csv(output_file, index=False)

    print("Prediction completed successfully.")
    print(f"Number of predictions: {len(predictions):,}")
    print(f"Saved to: {output_file}")
    print(predictions.head(10).to_string(index=False))
